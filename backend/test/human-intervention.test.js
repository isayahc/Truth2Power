import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';

test('challenge -> inbox -> verified public PDF import -> idempotent offline resume',async(t)=>{
  const root=mkdtempSync(join(tmpdir(),'SYN-human-handoff-'));
  process.env.AUDIT_DIR=root;process.env.T2P_REVIEW_DIRECTORY=join(root,'live');
  const {reportingRoute}=await import('../audit/reporting-api.js');
  const {openStore,claim}=await import('../audit/store.js');
  const {enqueuePipeline,failPipeline}=await import('../audit/pipeline-store.js');
  const {runPipeline}=await import('../audit/pipeline.js');
  const db=openStore();t.after(()=>{db.close();rmSync(root,{recursive:true,force:true})});
  const id=enqueuePipeline(db,{hospital_key:'798',mode:'full_audit',year:2026,review_date:'2026-11-10',request_key:'SYN-challenge'});
  failPipeline(db,claim(db),{code:'website_verification_required',diagnostic:{http_status:403,source_url:'https://public.example/financial-assistance'}});
  assert.equal(claim(db),null);
  const call=(path,body,headers={'x-review-request':'1'})=>reportingRoute({rawPath:'/api/pilot/v1'+path,headers,body:body===undefined?undefined:JSON.stringify(body),requestContext:{http:{method:body===undefined?'GET':'POST'}}});
  const base=`/runs/audit-run-${id}/intervention`;
  assert.equal(JSON.parse(call('/interventions').body).items.length,1);
  assert.equal(JSON.parse(call(`/runs/audit-run-${id}`).body).status,'needs_human');
  assert.equal(call(base+'/resume',{confirm:true}).statusCode,400);
  const pdf=execFileSync(process.env.T2P_PYTHON||'python',['-c',"import io,sys;from pypdf import PdfWriter;w=PdfWriter();w.add_blank_page(width=100,height=100);w.add_metadata({'/Title':'SYN public blank test document'});buffer=io.BytesIO();w.write(buffer);sys.stdout.buffer.write(buffer.getvalue())"]);
  const body={source_url:'https://public.example/SYN-blank.pdf',retrieved_at:'2026-11-09T12:00:00Z',language:'en',public_document:true,bytes:pdf.toString('base64')};
  assert.equal(call(base+'/documents',body,{}).statusCode,403);
  assert.equal(call(base+'/documents',{...body,public_document:false}).statusCode,400);
  assert.equal(call(base+'/documents',{...body,source_url:'https://127.0.0.1/secret'}).statusCode,400);
  assert.equal(call(base+'/documents',{...body,bytes:Buffer.from('%PDF-not-a-real-document').toString('base64')}).statusCode,400);
  const imported=call(base+'/documents',body);
  assert.equal(imported.statusCode,201,imported.body);
  assert.equal(call(base+'/documents',body).statusCode,200);
  const resumed=call(base+'/resume',{confirm:true});assert.equal(resumed.statusCode,202,resumed.body);
  assert.equal(JSON.parse(call(base+'/resume',{confirm:true}).body).audit_run_id,JSON.parse(resumed.body).audit_run_id);
  assert.equal(JSON.parse(call('/interventions').body).items.length,0);
  const job=claim(db);assert.equal(job.context.mode,'replay');assert.ok(job.context.manual_import);
  const bundle=await runPipeline(db,job);
  assert.equal(bundle.report.findings.length,17);
  const source=bundle.input.sources.find(s=>s.source_id===body.source_url);
  assert.equal(source.snapshot.retrieved_at,body.retrieved_at);
  assert.equal(source.snapshot.sha256,JSON.parse(imported.body).sha256);
  assert.equal(source.role,'unclassified');
});
