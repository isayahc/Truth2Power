test("Little Falls full saved summary chain resolves S with both languages and preserves all 17 outcomes", async () => {
  const unzip = spawnSync(process.env.T2P_PYTHON || "python", ["-m", "zipfile", "-e", "docs/validation/pilot-wave-one-evidence.zip", root]);
  assert.equal(unzip.status, 0);
  enqueuePipeline(db, { hospital_key: "362", year: 2026, review_date: "2026-11-09", mode: "replay", request_key: "SYN-public-replay", evidence_root: root });
  const b = await runPipeline(db, claim(db));
  const s = b.report.findings.find((f) => f.css_column === "S");
  assert.equal(s.result, "yes");
  assert.equal(b.report.findings.length, 17);
  assert.equal(b.report.final_grade, null);
  const inputS = b.input.findings.find((f) => f.measure_id === s.measure_id);
  const anchors = inputS.evidence.filter((e) => e.locator.startsWith("link "));
  assert.equal(new Set(anchors.map((e) => e.source_id)).size, 2);
  assert.equal(inputS.observed[0].value.links.length, 2);
  assert.ok(inputS.evidence.some((e) => e.quote.includes('Little Falls Hospital')));
  assert.equal(hospitalPage("362").revision, b.id);
  assert.equal(overview().hospitals.find((h) => h.hospital_key === "362").revision, b.id);
  assert.deepEqual(grade(b.input, { root: process.env.T2P_REVIEW_DIRECTORY }), b.report);
  const corrupt = structuredClone(b.input);
  corrupt.findings.find((f) => f.measure_id === s.measure_id).evidence[0].quote = "SYN invented link";
  assert.throws(() => grade(corrupt, { root: process.env.T2P_REVIEW_DIRECTORY }), /excerpt/);
  const doc = b.input.sources.find((s) => s.role === "policy_summary" && s.language === "es");
  const path = join(process.env.T2P_REVIEW_DIRECTORY, doc.snapshot.artifact_path), bytes = readFileSync(path);
  writeFileSync(path, "SYN corrupted");
  assert.throws(() => grade(b.input, { root: process.env.T2P_REVIEW_DIRECTORY }), /SHA-256/);
  writeFileSync(path, bytes);
  assert.equal(publications().bundles.length, 1);
  assert.equal(history(db, "362"), null, "Legacy fixture history must not return the integrated envelope");
  const pendingPilot = enqueuePipeline(db, { hospital_key: "362", year: 2026, review_date: "2026-11-09", mode: "replay", request_key: "SYN-next-public", evidence_root: root });
  const legacy = enqueue(db, 2026);
  assert.notEqual(legacy, pendingPilot, "A pending pilot cannot satisfy a legacy fixture request");
  assert.equal(db.prepare("SELECT rule FROM jobs WHERE id=?").get(legacy).rule, "application.fpl_guidelines");
});

test("posting graph rejects wrong-campus evidence, disconnected links and traversal beyond three hops", () => {
  const start = 'https://example.org/financial', target = 'https://example.org/es.pdf';
  const page = (url) => ({ source_id: url, role: 'landing_page', snapshot: { sha256: 'a', snapshot_id: 'a' } });
  const doc = { source_id: target, role: 'policy_summary', snapshot: { sha256: 'b', snapshot_id: 'b' } };
  const edge = (url) => ({ locator: 'link ' + url, text: 'SYN label', status: 'extracted' });
  const text = { locator: 'page 1', text: 'SYN campus', status: 'extracted' };
  const known = [{ hospital_key: '362', role: 'policy_summary', sha256: 'b', locator: 'page 1', quote: 'SYN campus' }];
  assert.equal(postingPaths([page(start), doc], { [start]: [edge(target)], [target]: [text] }, start, ['policy_summary'], known, '1002').length, 0);
  assert.equal(postingPaths([page(start), doc], { [target]: [text] }, start, ['policy_summary'], known, '362').length, 0);
  const pages = [start, ...[1, 2, 3].map((i) => `https://example.org/resources/${i}`)];
  const extracted = Object.fromEntries(pages.map((p, i) => [p, [edge(pages[i + 1] || target)]]));
  extracted[target] = [text];
  assert.equal(postingPaths([...pages.map(page), doc], extracted, start, ['policy_summary'], known, '362', 3).length, 0);
  extracted[pages[2]] = [edge(target)];
  assert.equal(postingPaths([...pages.map(page), doc], extracted, start, ['policy_summary'], known, '362').length, 1);
});

test("normalization reuses verified source facts but rejects stale context, altered identity and qualitative labels", () => {
  const fixture = JSON.parse(readFileSync('docs/grading/examples/SYN-2026.json'));
  const current = structuredClone(fixture); current.assessment_id = 'SYN-new-assessment';
  const first = normalizeObservations(fixture, current, resolve('docs/grading/examples'));
  assert.ok(first.accepted.length >= 3);
  assert.ok(first.accepted.every((o) => o.context.assessment_id === current.assessment_id));
  const stale = structuredClone(fixture); stale.guideline_year = 2025;
  assert.equal(normalizeObservations(stale, current, resolve('docs/grading/examples')).accepted.length, 0);
  const changed = structuredClone(current); changed.sources.forEach((s) => { s.language = 'und'; });
  assert.equal(normalizeObservations(fixture, changed, resolve('docs/grading/examples')).accepted.length, 0);
  const model = structuredClone(fixture);
  model.findings.forEach((f) => f.observed.forEach((o) => { o.method = 'human_interpretation'; }));
  assert.equal(normalizeObservations(model, current, resolve('docs/grading/examples')).accepted.length, 0);
  const disputed = structuredClone(fixture);
  const id = first.accepted[0].measure_id;
  disputed.origin = { finding_review: { [id]: { status: 'conflict' } } };
  const conflict = normalizeObservations(disputed, current, resolve('docs/grading/examples'));
  assert.ok(!conflict.accepted.some((o) => o.measure_id === id));
  assert.ok(conflict.rejected.some((reason) => reason.includes('conflicting review')));
});
